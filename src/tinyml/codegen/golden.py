"""Golden vectors (docs/contracts/golden-vectors.md): test windows plus Python's expected answers,
the C header that bakes them into firmware, and the comparison of firmware output with Python.
"""

from __future__ import annotations

import base64
import struct
from typing import Any

import numpy as np

from tinyml.contracts import GoldenSet, GoldenVector
from tinyml.ml.models import Model, Prediction

MAX_GOLDEN_BYTES = 512 * 1024  # keeps the harness image small enough for every emulator
SCORE_RTOL = 2e-3


def select_windows(true_labels: np.ndarray, pred: Prediction, max_count: int, window_bytes: int,
                   seed: int) -> np.ndarray:
    """Pick a mix of every (true, predicted) combination, at most max_count windows."""
    limit = max(4, min(max_count, MAX_GOLDEN_BYTES // max(window_bytes, 1)))
    rng = np.random.default_rng(seed)
    groups: dict[tuple[str, int], list[int]] = {}
    for i, (t, p) in enumerate(zip(true_labels, pred.labels, strict=True)):
        groups.setdefault((str(t), int(p)), []).append(i)
    chosen: list[int] = []
    for key in sorted(groups):
        members = groups[key]
        take = max(1, int(round(limit * len(members) / len(true_labels))))
        picked = rng.choice(members, size=min(take, len(members)), replace=False)
        chosen.extend(int(i) for i in picked)
    if len(chosen) > limit:
        chosen = list(rng.choice(chosen, size=limit, replace=False))
    remaining = [i for i in range(len(true_labels)) if i not in set(chosen)]
    while len(chosen) < limit and remaining:
        chosen.append(remaining.pop(int(rng.integers(0, len(remaining)))))
    return np.array(sorted(chosen), dtype=int)


def build_golden(
    X: np.ndarray,
    recordings: np.ndarray,
    true_labels: np.ndarray,
    features: np.ndarray,
    pred: Prediction,
    model: Model,
    feature_names: list[str],
    tolerances: list[dict[str, float]],
    axes: list[str],
) -> GoldenSet:
    vectors = []
    for i in range(len(X)):
        raw = np.ascontiguousarray(X[i], dtype="<f4").tobytes()
        vectors.append(GoldenVector(
            id=i,
            recording=str(recordings[i]),
            true_label=str(true_labels[i]),
            input_b64=base64.b64encode(raw).decode(),
            expected_label=int(pred.labels[i]),
            expected_score=float(pred.scores[i]),
            expected_features=[float(v) for v in features[i]],
            margin=0.0,
            borderline=bool(pred.borderline[i]),
        ))
    return GoldenSet(
        window_samples=int(X.shape[1]),
        axes=axes,
        feature_names=feature_names,
        feature_tolerances=tolerances,
        score_rtol=SCORE_RTOL,
        score_exact=model.quantization == "int8",
        vectors=vectors,
    )


def decode_input(vector: GoldenVector, samples: int, axes: int) -> np.ndarray:
    return np.frombuffer(base64.b64decode(vector.input_b64), dtype="<f4").reshape(samples, axes)


def header(golden: GoldenSet) -> str:
    n_axes = len(golden.axes)
    lines = [
        "/* Golden test windows. Generated by tinyml; inputs are exact float32 values. */",
        "#ifndef TINYML_GOLDEN_VECTORS_H",
        "#define TINYML_GOLDEN_VECTORS_H",
        "",
        f"#define TINYML_GOLDEN_COUNT {len(golden.vectors)}",
        "",
        f"static const float tinyml_golden_inputs[TINYML_GOLDEN_COUNT][{golden.window_samples * n_axes}] = {{",
    ]
    for vec in golden.vectors:
        values = decode_input(vec, golden.window_samples, n_axes).ravel()
        lines.append("    {")
        for start in range(0, len(values), 6):
            chunk = values[start:start + 6]
            lines.append("        " + ", ".join(float(np.float32(v)).hex() + "f" for v in chunk) + ",")
        lines.append("    },")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def _bits_to_float(text: str) -> float:
    return struct.unpack("<f", struct.pack("<I", int(text, 16)))[0]


def parse_output(text: str) -> tuple[dict[int, dict[str, Any]], int | None, bool]:
    """Parse harness output into {id: {label, score, features}}, the timing value, and whether it finished."""
    rows: dict[int, dict[str, Any]] = {}
    timing = None
    for line in text.splitlines():
        parts = line.strip().split()
        if not parts:
            continue
        if parts[0] == "T" and len(parts) >= 2 and parts[1].isdigit():
            timing = int(parts[1])
        elif parts[0] == "W" and len(parts) >= 4:
            try:
                rows[int(parts[1])] = {
                    "label": int(parts[2]),
                    "score": _bits_to_float(parts[3]),
                    "features": [_bits_to_float(p) for p in parts[4:]],
                }
            except ValueError:
                continue
    return rows, timing, "TINYML DONE" in text


def compare(golden: GoldenSet, rows: dict[int, dict[str, Any]], finished: bool) -> dict[str, Any]:
    failures: list[dict[str, Any]] = []
    label_matches = borderline = borderline_mismatches = 0
    worst_ratio = 0.0
    worst_feature = None
    for vec in golden.vectors:
        got = rows.get(vec.id)
        if got is None:
            failures.append({"id": vec.id, "reason": "no output for this window"})
            continue
        if vec.borderline:
            borderline += 1
        if got["label"] == vec.expected_label:
            label_matches += 1
        elif vec.borderline:
            borderline_mismatches += 1
        else:
            failures.append({"id": vec.id, "reason": f"label {got['label']} != expected {vec.expected_label}"})
        if len(got["features"]) != len(vec.expected_features):
            failures.append({"id": vec.id, "reason": "wrong number of features"})
            continue
        for j, (c_val, py_val) in enumerate(zip(got["features"], vec.expected_features, strict=True)):
            tol = golden.feature_tolerances[j]
            allowed = tol["atol"] + tol["rtol"] * abs(py_val)
            diff = abs(c_val - py_val)
            ratio = diff / allowed if allowed > 0 else (0.0 if diff == 0 else float("inf"))
            if ratio > worst_ratio:
                worst_ratio, worst_feature = ratio, golden.feature_names[j]
            if diff > allowed and not np.isnan(py_val):
                failures.append({"id": vec.id, "reason": f"feature {golden.feature_names[j]}: C {c_val:.7g} vs "
                                 f"Python {py_val:.7g} (allowed ±{allowed:.3g})"})
        if not vec.borderline and got["label"] == vec.expected_label:
            exp = vec.expected_score
            allowed = SCORE_RTOL * (1.0 + abs(exp))
            if golden.score_exact:
                allowed = max(allowed, 1e-6 * abs(exp))
            if abs(got["score"] - exp) > allowed:
                failures.append({"id": vec.id, "reason": f"score C {got['score']:.7g} vs Python {exp:.7g}"})
    if not finished:
        failures.append({"id": -1, "reason": "firmware did not finish (crash or timeout)"})
    return {
        "windows": len(golden.vectors),
        "label_matches": label_matches,
        "borderline": borderline,
        "borderline_mismatches": borderline_mismatches,
        "worst_feature": worst_feature,
        "worst_tolerance_used": round(worst_ratio, 4),
        "failures": failures[:50],
        "passed": not failures,
    }
